// Retourne une fonction t(key) pour la langue donnée (fallback FR)
export function useTranslations(lang) {
  const L = ui[lang] ? lang : defaultLang;
  return function t(key) {
    return ui[L][key] ?? ui[defaultLang][key] ?? key;
  };
}
